#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
policy_dir="${repo_root}/.policy-bot"
base_policy="${policy_dir}/base-policy.yml"
repo_policy="${policy_dir}/repo-policy.yml"
output_policy="${repo_root}/.policy.yml"

for required_file in "$base_policy" "$repo_policy"; do
  if [[ ! -f "$required_file" ]]; then
    echo "missing policy source file: $required_file" >&2
    exit 1
  fi
done

tmp_policy="$(mktemp)"
cleanup() {
  rm -f "$tmp_policy"
}
trap cleanup EXIT

{
  echo "# Code generated by scripts/render-policy-bot-policy.sh from .policy-bot/base-policy.yml and .policy-bot/repo-policy.yml. DO NOT EDIT DIRECTLY."
  awk \
    -v repo_policy="$repo_policy" '
      function insert_section(path, section, fallback, line, active, marker, emitted) {
        active = 0
        emitted = 0
        while ((getline line < path) > 0) {
          if (line ~ /^[[:space:]]*#[[:space:]]*policy-bot-render:/) {
            marker = line
            sub(/^[[:space:]]*#[[:space:]]*policy-bot-render:/, "", marker)
            sub(/[[:space:]]*$/, "", marker)
            active = (marker == section)
          } else if (active && line !~ /^[[:space:]]*$/ && line !~ /^[[:space:]]*#/) {
            print line
            emitted = 1
          }
        }
        close(path)
        if (!emitted && fallback != "") {
          print fallback
        }
      }

      /^[[:space:]]*#[[:space:]]*policy-bot-render:repo-trusted-automation-approvals[[:space:]]*$/ {
        insert_section(repo_policy, "repo-trusted-automation-approvals", $0)
        next
      }

      /^[[:space:]]*#[[:space:]]*policy-bot-render:repo-human-review-requirements[[:space:]]*$/ {
        insert_section(repo_policy, "repo-human-review-requirements", $0)
        next
      }

      /^[[:space:]]*#[[:space:]]*policy-bot-render:repo-required-approvals[[:space:]]*$/ {
        insert_section(repo_policy, "repo-required-approvals", "")
        next
      }

      /^[[:space:]]*#[[:space:]]*policy-bot-render:repo-human-reviewer-teams[[:space:]]*$/ {
        insert_section(repo_policy, "repo-human-reviewer-teams", $0)
        next
      }

      /^[[:space:]]*#[[:space:]]*policy-bot-render:repo-approval-rules[[:space:]]*$/ {
        insert_section(repo_policy, "repo-approval-rules", "")
        next
      }

      { print }
    ' "$base_policy"
} > "$tmp_policy"

mv "$tmp_policy" "$output_policy"
